import { test, expect, type BrowserContext, type Route } from "@playwright/test";
import path from "node:path";
import { Either } from "effect";
import { describePath, fileUploadEdgePaths, type ModelEvent } from "@/components/file-upload.model";
import uploadText from "@/locales/en/upload.json" with { type: "json" };

/**
 * FileUpload wiring, on paths generated from app/components/file-upload.machine.ts
 * with xstate/graph.
 *
 * The machine's unit tests already cover every transition. This spec checks
 * the seam they can't see: each DOM event reaches the machine, and each state
 * renders what it should. So it runs a handful of the generated paths, chosen
 * so every binding and every view shows up at least once, not all of them.
 *
 * Each test replays its path on /admin/kitchen-sink#upload and checks
 * `data-state` after every step. The upload request is held open by a route
 * mock and released when the path reaches the upload actor's done event, so
 * `uploading` is observable and the reply (ok, refused or a dropped connection)
 * comes from the model.
 * The real upload to R2 is walked by feature-verifier, not here.
 *
 * Catches: a DOM event that no longer reaches the machine, a state the markup
 * renders wrong (e.g. "Upload another" leaving the success panel up, or
 * i18next escaping the key), and drift between the machine and the markup.
 */

const MAX = 1024 * 1024; // must match <FileUpload maxSize> on the kitchen-sink page
const small = new File(["hello"], "small.txt", { type: "text/plain" });
const big = new File([new Uint8Array(MAX + 1)], "big.bin", { type: "application/octet-stream" });

// One path per binding or view. Names come from describePath; the first test
// fails if the machine stops generating one of them.
const WIRING = [
  "DRAG_ENTER → DRAG_LEAVE → idle", // drag in and out, the dragging view
  "PICK small.txt → upload ok → success", // file picker, uploading and success views
  "PICK small.txt → upload ok → RESET → idle", // "Upload another" (the old reset bug)
  "PICK small.txt → upload refused → failed", // the route's refusal message
  "PICK small.txt → upload refused → RESET → idle", // "Try again"
  "PICK small.txt → upload unreachable → failed", // a dropped connection, the unreachable message
  "PICK big.bin → failed", // the size limit, with no request sent
] as const;

const named = fileUploadEdgePaths({ maxSize: MAX, small, big }).map((statePath) => {
  const end = String(statePath.state.value);
  const name = describePath(statePath.steps as ReadonlyArray<{ event: ModelEvent }>, end);
  return { statePath, end, name };
});
const paths = named.filter((p) => (WIRING as ReadonlyArray<string>).includes(p.name));

const AUTH = path.join("test-results", ".auth", "file-upload-admin.json");

// Sign in through the Better Auth API, not the form: on a cold dev server the
// form can be submitted before hydration and the login silently fails.
const login = async (context: BrowserContext, baseURL: string) => {
  const res = await context.request.post("/api/auth/sign-in/email", {
    headers: { Origin: baseURL },
    data: { email: "admin@preview.local", password: "Password123!" },
  });
  expect(res.ok(), `sign-in returned ${res.status()}`).toBe(true);
};

test.describe("FileUpload paths", () => {
  // One login for the file, in one worker: a login per test trips Better
  // Auth's sign-in rate limit.
  test.describe.configure({ mode: "default" });
  test.use({ storageState: AUTH });
  test.beforeAll(async ({ browser, baseURL }) => {
    const context = await browser.newContext({ storageState: undefined, baseURL });
    await login(context, baseURL ?? "");
    await context.storageState({ path: AUTH });
    await context.close();
  });

  test("every wiring path is still generated by the machine", () => {
    expect(paths.map((p) => p.name).sort()).toEqual([...WIRING].sort());
  });

  for (const { statePath, end, name } of paths) {
    // The smoke videos record one golden and one error path.
    const tag =
      name === "PICK small.txt → upload ok → success"
        ? "@golden"
        : name === "PICK small.txt → upload refused → failed"
          ? "@error"
          : undefined;

    test(name, tag ? { tag } : {}, async ({ page }) => {
      // Uploads wait here until the path's done event says how to answer.
      const held: Route[] = [];
      await page.route("**/api/upload-file", (route) => {
        held.push(route);
      });

      await page.goto("/admin/kitchen-sink#upload");
      const root = page.getByTestId("file-upload");
      const dropzone = page.getByTestId("file-upload-dropzone");
      await expect(root).toHaveAttribute("data-state", "idle");

      // The server renders data-state="idle" too, so "loaded" does not mean
      // React has hydrated, and networkidle can hang on the dev server. On a
      // cold dev server the first load can also die on Vite's "Outdated
      // Optimize Dep" 504s. Prove the machine is live with a drag in and out,
      // reloading until a handler answers.
      await expect(async () => {
        await dropzone.dispatchEvent("dragover");
        if ((await root.getAttribute("data-state")) !== "dragging") {
          await page.reload();
          throw new Error("FileUpload has not hydrated yet");
        }
      }).toPass({ timeout: 60_000 });
      await dropzone.dispatchEvent("dragleave");
      await expect(root).toHaveAttribute("data-state", "idle");

      for (const step of statePath.steps) {
        const event = step.event as ModelEvent | { type: "xstate.init" };
        switch (event.type) {
          case "xstate.init":
            break;
          case "DRAG_ENTER":
            await dropzone.dispatchEvent("dragover");
            break;
          case "DRAG_LEAVE":
            await dropzone.dispatchEvent("dragleave");
            break;
          case "PICK":
            await page.getByTestId("file-upload-input").setInputFiles({
              name: event.file.name,
              mimeType: event.file.type,
              buffer: Buffer.from(await event.file.arrayBuffer()),
            });
            break;
          case "RESET":
            await page.getByTestId("file-upload-reset").click();
            break;
          case "xstate.done.actor.upload": {
            await expect.poll(() => held.length).toBe(1);
            const route = held.shift() as Route;
            await Either.match(event.output, {
              onRight: ({ key }) => route.fulfill({ json: { success: true, key } }),
              // No readable reply: drop the connection.
              onLeft: (e) =>
                e._tag === "ExternalServiceError"
                  ? route.abort("failed")
                  : route.fulfill({ status: 400, json: { success: false, error: e.message } }),
            });
            break;
          }
        }
        await expect(root).toHaveAttribute("data-state", String(step.state.value));
      }

      // What each end state must show, beyond its data-state.
      const { context } = statePath.state;
      if (end === "success") {
        await expect(page.getByTestId("file-upload-key")).toContainText(context.key ?? "");
      }
      if (end === "failed") {
        await expect(page.getByTestId("file-upload-error")).toBeVisible();
        if (context.error?.reason === "unreachable") {
          await expect(page.getByTestId("file-upload-error")).toContainText(uploadText.unreachable);
        }
      } else {
        await expect(page.getByTestId("file-upload-error")).toHaveCount(0);
      }
      if (end === "idle" || end === "dragging") {
        await expect(dropzone).toBeVisible();
      }
      // A path with no upload step must not have sent a request.
      const uploads = (statePath.steps as ReadonlyArray<{ event: ModelEvent }>).filter(
        (s) => s.event.type === "xstate.done.actor.upload",
      );
      if (uploads.length === 0) expect(held).toHaveLength(0);
    });
  }
});
