import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { buildWranglerConfig, DUMMY_INPUT, parseJsonc, RATE_LIMITS, readWranglerJsonc, stripJsonc, writeWranglerJsonc } from "../lib/wrangler-config";
import { RATE_LIMIT_BINDINGS, RATE_LIMIT_PERIOD_SECONDS } from "../../app/lib/constants/rate-limit";

interface RateLimitEntry {
  name: string;
  namespace_id: string;
  simple: { limit: number; period: number };
}

interface WranglerShape {
  ratelimits?: RateLimitEntry[];
  env: Record<"preview" | "staging", { ratelimits?: RateLimitEntry[]; d1_databases?: { database_name: string }[]; r2_buckets?: { bucket_name: string }[] }>;
}

const committed = JSON.parse(stripJsonc(fs.readFileSync(path.join(__dirname, "..", "..", "wrangler.jsonc"), "utf-8"))) as WranglerShape;

const built = buildWranglerConfig(DUMMY_INPUT) as WranglerShape;

describe("buildWranglerConfig", () => {
  it("builds the same rate-limit bindings wrangler.jsonc holds, in both blocks, whatever names and ids setup wrote around them", () => {
    expect(built.ratelimits).toEqual(committed.ratelimits);
    expect(built.env.preview.ratelimits).toEqual(committed.env.preview.ratelimits);
  });

  it("binds every rate-limit rule the app names, at top level and in preview", () => {
    const names = Object.values(RATE_LIMIT_BINDINGS).sort();
    expect(built.ratelimits?.map((entry) => entry.name).sort()).toEqual(names);
    expect(built.env.preview.ratelimits?.map((entry) => entry.name).sort()).toEqual(names);
  });

  it("keeps the preview counters apart from production by giving them other namespace ids", () => {
    const top = new Set(built.ratelimits?.map((entry) => entry.namespace_id));
    const preview = built.env.preview.ratelimits?.map((entry) => entry.namespace_id) ?? [];
    expect(preview).toHaveLength(RATE_LIMITS.length);
    expect(preview.filter((id) => top.has(id))).toEqual([]);
  });

  it("uses the period the app sends as Retry-After, so the header never undercounts the wait", () => {
    const periods = [...(built.ratelimits ?? []), ...(built.env.preview.ratelimits ?? [])].map((entry) => entry.simple.period);
    expect(new Set(periods)).toEqual(new Set([RATE_LIMIT_PERIOD_SECONDS]));
  });

  it("builds the same env blocks and staging rate limits the committed wrangler.jsonc holds, whatever ids, names or vars setup and the owner wrote into it, so that setup never drops a block the repo deploys", () => {
    expect(Object.keys(committed.env).sort()).toEqual(Object.keys(built.env).sort());
    expect(built.env.staging.ratelimits).toEqual(committed.env.staging.ratelimits);
  });

  it("gives staging its own database, bucket and rate-limit counters, so that a staging deploy or test never touches production or preview data", () => {
    const staging = built.env.staging;
    expect(staging.d1_databases?.[0]?.database_name).toBe("cf-saas-starter-react-router-db-staging");
    expect(staging.r2_buckets?.[0]?.bucket_name).toBe("cf-saas-starter-react-router-bucket-staging");
    const others = new Set([...(built.ratelimits ?? []), ...(built.env.preview.ratelimits ?? [])].map((entry) => entry.namespace_id));
    const ids = staging.ratelimits?.map((entry) => entry.namespace_id) ?? [];
    expect(ids).toHaveLength(RATE_LIMITS.length);
    expect(ids.filter((id) => others.has(id))).toEqual([]);
  });

  it("drops the R2 bucket from both blocks when setup runs without R2", () => {
    const withoutR2 = buildWranglerConfig({ ...DUMMY_INPUT, enableR2: false }) as Record<string, unknown> & {
      env: { preview: Record<string, unknown>; staging: Record<string, unknown> };
    };
    expect(withoutR2).not.toHaveProperty("r2_buckets");
    expect(withoutR2.env.preview).not.toHaveProperty("r2_buckets");
    expect(withoutR2.env.staging).not.toHaveProperty("r2_buckets");
    expect(withoutR2).toHaveProperty("ratelimits");
  });
});

describe("parseJsonc", () => {
  it("whole-line comments are dropped: teardown read a commented wrangler.jsonc as invalid", () => {
    const text = '// header\n{\n  // the worker\n  "name": "w",\n  "d1_databases": []\n}\n';
    expect(parseJsonc<{ name: string }>(text)).toEqual({ name: "w", d1_databases: [] });
  });

  it("text that is not JSON gives null, never a throw: teardown reports and goes on", () => {
    expect(parseJsonc("{ not json")).toBeNull();
  });
});

describe("writeWranglerJsonc and readWranglerJsonc", () => {
  it("round-trips a config through a file, header comment included", () => {
    const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "wrangler-")), "wrangler.jsonc");
    const config = { ...buildWranglerConfig(DUMMY_INPUT), vars: { BETTER_AUTH_URL: "https://app.example.com" } };
    writeWranglerJsonc(config, file);
    expect(fs.readFileSync(file, "utf-8").startsWith("// Generated by scripts/first-time-setup.ts")).toBe(true);
    expect(readWranglerJsonc(file)).toEqual(config);
  });

  it("reads a missing file as null", () => {
    expect(readWranglerJsonc(path.join(os.tmpdir(), "no-such-wrangler-160.jsonc"))).toBeNull();
  });
});
