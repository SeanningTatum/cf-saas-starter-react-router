import fs from "node:fs";
import path from "node:path";
import {
  RATE_LIMIT_BINDINGS,
  RATE_LIMIT_PERIOD_SECONDS,
  RATE_LIMIT_REQUESTS_PER_PERIOD,
  type RateLimitBindingName,
} from "../../app/lib/constants/rate-limit";

export interface WranglerConfigInput {
  projectName: string;
  dbId: string;
  previewDbId: string;
  /**
   * Whether to include the R2 bucket bindings. Defaults to true so the
   * committed placeholder config and teardown keep R2 wired. Set false when
   * setup runs without R2 file storage.
   */
  enableR2?: boolean;
}

export interface RateLimitBinding {
  name: RateLimitBindingName;
  limit: number;
  namespaceId: string;
  previewNamespaceId: string;
}

export const RATE_LIMITS: ReadonlyArray<RateLimitBinding> = [
  { name: RATE_LIMIT_BINDINGS.signIn, limit: RATE_LIMIT_REQUESTS_PER_PERIOD.signIn, namespaceId: "1001", previewNamespaceId: "2001" },
  { name: RATE_LIMIT_BINDINGS.signUp, limit: RATE_LIMIT_REQUESTS_PER_PERIOD.signUp, namespaceId: "1002", previewNamespaceId: "2002" },
  { name: RATE_LIMIT_BINDINGS.authApi, limit: RATE_LIMIT_REQUESTS_PER_PERIOD.authApi, namespaceId: "1003", previewNamespaceId: "2003" },
  { name: RATE_LIMIT_BINDINGS.upload, limit: RATE_LIMIT_REQUESTS_PER_PERIOD.upload, namespaceId: "1004", previewNamespaceId: "2004" },
];

const rateLimitBindings = (namespaceIdOf: (binding: RateLimitBinding) => string) =>
  RATE_LIMITS.map((binding) => ({
    name: binding.name,
    namespace_id: namespaceIdOf(binding),
    simple: { limit: binding.limit, period: RATE_LIMIT_PERIOD_SECONDS },
  }));

const HEADER_COMMENT =
  "// Generated by scripts/first-time-setup.ts — real IDs are filled in by setup; teardown restores dummy values.";

/**
 * Builds the full wrangler.jsonc config object (top-level + "preview" env),
 * mirroring the committed wrangler.jsonc structure exactly.
 */
export function buildWranglerConfig(input: WranglerConfigInput): object {
  const { projectName, dbId, previewDbId, enableR2 = true } = input;

  const dbName = `${projectName}-db`;
  const bucketName = `${projectName}-bucket`;
  const previewDbName = `${dbName}-preview`;
  const previewBucketName = `${bucketName}-preview`;

  const r2Buckets = [{ binding: "BUCKET", bucket_name: bucketName }];
  const previewR2Buckets = [
    { binding: "BUCKET", bucket_name: previewBucketName },
  ];

  return {
    name: projectName,
    main: "workers/app.ts",
    compatibility_date: "2025-03-25",
    compatibility_flags: ["nodejs_compat"],
    assets: {
      directory: "build/client",
      binding: "ASSETS",
    },
    placement: {
      mode: "smart",
    },
    d1_databases: [
      {
        binding: "DATABASE",
        database_name: dbName,
        database_id: dbId,
        migrations_dir: "./drizzle",
      },
    ],
    ...(enableR2 ? { r2_buckets: r2Buckets } : {}),
    ai: {
      binding: "AI",
    },
    ratelimits: rateLimitBindings((binding) => binding.namespaceId),
    observability: {
      logs: {
        enabled: true,
        head_sampling_rate: 1,
        invocation_logs: true,
        persist: true,
      },
    },
    workers_dev: true,
    preview_urls: true,
    env: {
      preview: {
        workers_dev: true,
        preview_urls: true,
        d1_databases: [
          {
            binding: "DATABASE",
            database_name: previewDbName,
            database_id: previewDbId,
            migrations_dir: "./drizzle",
          },
        ],
        ...(enableR2 ? { r2_buckets: previewR2Buckets } : {}),
        ai: {
          binding: "AI",
        },
        ratelimits: rateLimitBindings((binding) => binding.previewNamespaceId),
        observability: {
          logs: {
            enabled: true,
            head_sampling_rate: 1,
            invocation_logs: true,
            persist: true,
          },
        },
      },
    },
  };
}

/** wrangler.jsonc text without its whole-line `//` comments, ready for JSON.parse. */
export function stripJsonc(text: string): string {
  return text.replace(/^\s*\/\/.*$/gm, "");
}

export function parseJsonc<T>(text: string): T | null {
  try {
    return JSON.parse(stripJsonc(text)) as T;
  } catch {
    return null;
  }
}

/**
 * Writes the given config object to the repo-root wrangler.jsonc, prefixed
 * with a header comment explaining that the file is generated/restored by
 * scripts/first-time-setup.ts and scripts/teardown.ts.
 */
export function writeWranglerJsonc(config: object): void {
  const wranglerJsonPath = path.join(__dirname, "..", "..", "wrangler.jsonc");

  const jsonContent =
    `${HEADER_COMMENT}\n` + JSON.stringify(config, null, 2) + "\n";

  fs.writeFileSync(wranglerJsonPath, jsonContent);
}

