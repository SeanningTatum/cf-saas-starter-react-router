const HEADER_COMMENT = "// Generated by scripts/first-time-setup.ts — real IDs are filled in by setup; teardown restores dummy values.";

const OBSERVABILITY = { logs: { enabled: true, head_sampling_rate: 1, invocation_logs: true, persist: true } };

const STAGING_ENV = "staging";

export const REMOTE_MIGRATION_TARGETS: ReadonlyArray<readonly [label: string, flags: string]> = [
  ["production", ""],
  ["preview", " --env preview"],
  [STAGING_ENV, ` --env ${STAGING_ENV}`],
];

export const resourceNames = (projectName: string) => ({
  dbName: `${projectName}-db`,
  bucketName: `${projectName}-bucket`,
  previewDbName: `${projectName}-db-preview`,
  previewBucketName: `${projectName}-bucket-preview`,
  stagingDbName: `${projectName}-db-${STAGING_ENV}`,
  stagingBucketName: `${projectName}-bucket-${STAGING_ENV}`,
});

interface EnvironmentBlock {
  dbName: string;
  dbId: string;
  bucketName: string;
  previewUrls: boolean;
  enableR2: boolean;
  namespaceIdOf: (binding: RateLimitBinding) => string;
}

const environmentBlock = (block: EnvironmentBlock) => ({
  workers_dev: true,
  preview_urls: block.previewUrls,
  d1_databases: [{ binding: "DATABASE", database_name: block.dbName, database_id: block.dbId, migrations_dir: "./drizzle" }],
  ...(block.enableR2 ? { r2_buckets: [{ binding: "BUCKET", bucket_name: block.bucketName }] } : {}),
  ai: { binding: "AI" },
  ratelimits: rateLimitBindings(block.namespaceIdOf),
  observability: OBSERVABILITY,
});

/**
 * Builds the full wrangler.jsonc config object (top-level, "preview" and
 * "staging" envs), mirroring the committed wrangler.jsonc structure exactly.
 */
export function buildWranglerConfig(input: WranglerConfigInput): object {
  const { projectName, dbId, previewDbId, stagingDbId, enableR2 = true } = input;
  const names = resourceNames(projectName);

  return {
    name: projectName,
    main: "workers/app.ts",
    compatibility_date: "2025-03-25",
    compatibility_flags: ["nodejs_compat"],
    assets: {
      directory: "build/client",
      binding: "ASSETS",
    },
    placement: {
      mode: "smart",
    },
    d1_databases: [{ binding: "DATABASE", database_name: names.dbName, database_id: dbId, migrations_dir: "./drizzle" }],
    ...(enableR2 ? { r2_buckets: [{ binding: "BUCKET", bucket_name: names.bucketName }] } : {}),
    ai: {
      binding: "AI",
    },
    ratelimits: rateLimitBindings((binding) => binding.namespaceId),
    observability: OBSERVABILITY,
    workers_dev: true,
    preview_urls: true,
    env: {
      preview: environmentBlock({
        dbName: names.previewDbName,
        dbId: previewDbId,
        bucketName: names.previewBucketName,
        previewUrls: true,
        enableR2,
        namespaceIdOf: (binding) => binding.previewNamespaceId,
      }),
      [STAGING_ENV]: environmentBlock({
        dbName: names.stagingDbName,
        dbId: stagingDbId,
        bucketName: names.stagingBucketName,
        previewUrls: false,
        enableR2,
        namespaceIdOf: (binding) => binding.stagingNamespaceId,
      }),
    },
  };
}

/** wrangler.jsonc text without its whole-line `//` comments, ready for JSON.parse. */
export function stripJsonc(text: string): string {
  return text.replace(/^\s*\/\/.*$/gm, "");
}

export function parseJsonc<T>(text: string): T | null {
  try {
    return JSON.parse(stripJsonc(text)) as T;
  } catch {
    return null;
  }
}

/**
 * Writes the given config object to the repo-root wrangler.jsonc, prefixed
 * with a header comment explaining that the file is generated/restored by
 * scripts/first-time-setup.ts and scripts/teardown.ts.
 */
export function writeWranglerJsonc(config: object): void {
  const wranglerJsonPath = path.join(__dirname, "..", "..", "wrangler.jsonc");

  const jsonContent = `${HEADER_COMMENT}\n${JSON.stringify(config, null, 2)}\n`;

  fs.writeFileSync(wranglerJsonPath, jsonContent);
}

